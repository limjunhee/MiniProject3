import pandas as pd
import matplotlib.pyplot as plt

plt.rc('font', family='Malgun Gothic')
plt.rc('axes', unicode_minus=False)

# ##############################################################################
#  배경. 음식점 개업·폐업 현황 (2021.01 ~ 2025.12)     → 보고서 [그림 1] [그림 2] [그림 3]
#   - 국세청은 월별 폐업자 수를 2024년부터만 공개 → 가동 사업자 수와 신규 사업자 수로 역산
#     폐업(이번 달) = 신규(이번 달) − (가동(이번 달) − 가동(지난달))
# ##############################################################################

# ==============================================================================
# [1] 월별 가동 사업자 수 (음식업)
#   - 2022·2023·2025년 파일 36개 : '성별' 시트, 0열 업태 / 4열 당월 / 5열 전월 / 7열 전년동월
#     → 한 파일에서 그 해와 작년 값을 같이 얻음
#   - 2021년 1월 파일 : 앞에 '순번' 열이 있어 한 칸씩 밀림 (1열 업태 / 5열 당월 / 6열 전월)
#     → 2020년 12월 값을 얻기 위해 사용
# ==============================================================================
가동 = {}                                     # 연월 → 가동 사업자 수
for 연도 in [2022, 2023, 2025]:
    for 월 in range(1, 13):
        d = pd.read_excel(f'./Data/월별/가동사업자_{연도}_{월:02d}.xlsx', sheet_name='성별', header=None)
        d[0] = d[0].astype(str).str.strip()
        행 = d[d[0] == '음식업'].iloc[0]                  # 음식업 블록의 첫 행 = 전국 합계
        가동[f'{연도}-{월:02d}'] = int(행[4])            # 당월
        가동[f'{연도 - 1}-{월:02d}'] = int(행[7])        # 전년동월
        if 월 == 1:
            가동[f'{연도 - 1}-12'] = int(행[5])          # 1월 파일의 전월 = 작년 12월

d = pd.read_excel('./Data/월별/가동사업자_2021_01.xlsx', sheet_name='성별', header=None)
d[1] = d[1].astype(str).str.strip()
행 = d[d[1] == '음식업'].iloc[0]
가동['2021-01'] = int(행[5])
가동['2020-12'] = int(행[6])

rows = []
for 연월, 값 in 가동.items():
    rows.append({'연월': 연월, '가동': 값})
stock = pd.DataFrame(rows).sort_values('연월').reset_index(drop=True)
stock['가동_전월'] = [None] + list(stock['가동'][:-1])     # 한 칸 아래로 밀어 '지난달 값' 열 만들기

# ==============================================================================
# [2] 월별 신규 사업자 수 (음식점업) : 신규사업자 현황Ⅱ 엑셀 5개 (2021~2025)
#   - 시트 (3)=1~6월, (4)=7~12월 / (3)시트는 '연간 계' 열이 하나 더 있어 4열부터, (4)시트는 3열부터
# ==============================================================================
rows = []
for 연도 in range(2021, 2026):
    for 시트, 시작월, 첫열 in [('(3)', 1, 4), ('(4)', 7, 3)]:
        d = pd.read_excel(f'./Data/신규사업자_{연도}.xlsx', sheet_name=시트, header=None)
        d[0] = d[0].astype(str).str.strip()
        행 = d[d[0] == '음식점업'].iloc[0]
        for k in range(6):
            rows.append({'연월': f'{연도}-{시작월 + k:02d}', '신규': int(행[첫열 + k])})
new = pd.DataFrame(rows)

# ==============================================================================
# [3] 월별 폐업 역산 + 연도별 합계
# ==============================================================================
m = stock.merge(new, on='연월').sort_values('연월').reset_index(drop=True)
m['폐업'] = m['신규'] - (m['가동'] - m['가동_전월'])
m['순증'] = m['신규'] - m['폐업']
m['연도'] = m['연월'].str[:4]
m['월'] = m['연월'].str[2:4] + '.' + m['연월'].str[5:7]          # '2021-01' → '21.01' (x축 글자)
print(m)

연합 = m.groupby('연도')[['신규', '폐업', '순증']].sum().reset_index()
# 역산 검증 : 국세청 공식 음식업 폐업자 수(개인)와 비교
공식 = [123794, 131801, 152520, 148123, 137467]                   # 2021 ~ 2025
연합['공식폐업'] = 공식
연합['오차(%)'] = (연합['폐업'] / 연합['공식폐업'] - 1) * 100
print(연합)

# ==============================================================================
# [그림 1] 음식점 연도별 개업 vs 폐업 + 순증
# ==============================================================================
fig, ax = plt.subplots(1, 2, figsize=(13, 5))
ax[0].plot(연합['연도'], 연합['신규'] / 10000, marker='o', color='royalblue', label='개업')
ax[0].plot(연합['연도'], 연합['폐업'] / 10000, marker='o', color='crimson', label='폐업(역산)')
ax[0].set_title('음식점 연도별 개업 vs 폐업 (만 명)')
ax[0].legend()
ax[0].grid(alpha=0.3)

색 = ['seagreen' if v >= 0 else 'crimson' for v in 연합['순증']]
막대 = ax[1].bar(연합['연도'], 연합['순증'] / 10000, color=색)
ax[1].bar_label(막대, fmt='%+.1f')
ax[1].set_title('음식점 연도별 순증 (개업 - 폐업, 만 명)')
ax[1].grid(alpha=0.3, axis='y')
plt.tight_layout()
plt.show()

# ==============================================================================
# [그림 2] 음식점 월별 개업 vs 폐업 + 순증 (x축은 3개월마다 표시)
# ==============================================================================
fig, ax = plt.subplots(2, 1, figsize=(13, 8))
ax[0].plot(m['월'], m['신규'], marker='.', color='royalblue', label='신규(개업)')
ax[0].plot(m['월'], m['폐업'], marker='.', color='crimson', label='폐업(역산)')
ax[0].set_ylabel('명')
ax[0].set_title('음식점 월별 개업 vs 폐업 (2021.01 ~ 2025.12)')
ax[0].legend()
ax[0].grid(alpha=0.3)

색 = ['seagreen' if v >= 0 else 'crimson' for v in m['순증']]
ax[1].bar(m['월'], m['순증'], color=색)
ax[1].set_ylabel('순증 (개업 - 폐업, 명)')
ax[1].set_title('월별 순증 — 빨간 막대 = 문 닫은 음식점이 더 많은 달')
ax[1].grid(alpha=0.3, axis='y')
for a in ax:
    a.set_xticks(range(0, len(m), 3))
    a.set_xticklabels(m['월'][::3])
plt.tight_layout()
plt.show()

# ==============================================================================
# [그림 3] 음식점 폐업 사유 : 국세청 「폐업자 현황 Ⅳ (폐업사유, 지역, 업태)」
#   - 시트 (2)·(3)·(4) = 일반·간이·면세 사업자 (= 개인사업자) → 3개 시트의 '음식업' 행을 더함
#   - 열 : 2 총계 / 3 사업부진 / 4 행정처분 / 5 계절사업 / 6 법인전환 / 7 면세포기·적용
#          8 양도·양수 / 9 해산·합병 / 10 기타
# ==============================================================================
사유 = ['총계', '사업부진', '행정처분', '계절사업', '법인전환', '면세포기적용', '양도양수', '해산합병', '기타']
rows = []
for 연도 in range(2021, 2026):
    row = {'연도': str(연도)}
    for s in 사유:
        row[s] = 0
    for 시트 in ['(2)', '(3)', '(4)']:
        d = pd.read_excel(f'./Data/폐업사유_{연도}.xlsx', sheet_name=시트, header=None)
        업태부분 = False
        for i in range(9, d.shape[0]):
            이름 = str(d.iloc[i, 0]).replace('\n', '').strip()
            if 이름 == '업태별':
                업태부분 = True                    # '업태별' 아래부터 업태 행
            if 업태부분 and 이름 == '음식업':
                for k in range(9):
                    row[사유[k]] = row[사유[k]] + int(d.iloc[i, 2 + k])
    rows.append(row)
음식 = pd.DataFrame(rows)
음식['사업부진비중'] = 음식['사업부진'] / 음식['총계'] * 100
print(음식)

fig, ax = plt.subplots(1, 2, figsize=(14, 5))
아래 = [0] * len(음식)                              # 막대를 쌓기 위한 바닥 높이
for s in ['사업부진', '양도양수', '행정처분', '법인전환', '해산합병', '계절사업', '면세포기적용', '기타']:
    값 = list(음식[s] / 10000)
    ax[0].bar(음식['연도'], 값, bottom=아래, label=s)
    아래 = [아래[k] + 값[k] for k in range(len(값))]
ax[0].set_title('음식점 연도별 폐업 사유 구성 (만 명)')
ax[0].legend(fontsize=8, ncol=2)

ax[1].plot(음식['연도'], 음식['사업부진비중'], marker='o', color='crimson')
for k in range(len(음식)):
    ax[1].text(k, 음식['사업부진비중'][k] + 0.3, f"{음식['사업부진비중'][k]:.1f}", ha='center')
ax[1].set_ylim(45, 60)
ax[1].set_title("음식점 '사업부진(장사가 안 돼서)' 폐업 비중 (%)")
ax[1].grid(alpha=0.3)
plt.tight_layout()
plt.show()