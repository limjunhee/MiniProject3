import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

plt.rc('font', family='Malgun Gothic')
plt.rc('axes', unicode_minus=False)

# ##############################################################################
#  배경 1. 월별로 본 자영업(소매·음식) 개업·폐업 — 2021.02 ~ 2025.12 (59개월)
#   - 국세청은 월별 폐업자 수를 2024년부터만 공개 → 가동 사업자 수와 신규 사업자 수로 역산
#   - 소매+음식 전체로는 아직 개업이 더 많지만 그 차이(순증)가 빠르게 줄어듦
#   - 업태를 나눠 보면 음식점은 2024년부터 폐업이 개업보다 많아짐 → 음식점이 더 심각
# ##############################################################################

# ==============================================================================
# [1] 월별 가동 사업자 수 : 엑셀 36개 (2022·2023·2025 각 12개월)
#   - '성별' 시트, 업태 블록의 첫 행 = 전국 합계
#   - 열 4: 당월, 열 5: 전월, 열 7: 전년동월  → 한 파일에서 2개 연도 값을 얻음
#     (2022년 파일 → 2021·2022, 2023년 파일 → 2022·2023, 2025년 파일 → 2024·2025)
# ==============================================================================
가동 = {}                                     # (연월, 업태) → 가동 사업자 수  (같은 연월이 두 파일에 있으면 덮어씀)
for 연도 in [2022, 2023, 2025]:
    for 월 in range(1, 13):
        d = pd.read_excel(f'./Data/월별/가동사업자_{연도}_{월:02d}.xlsx', sheet_name='성별', header=None)
        d[0] = d[0].astype(str).str.strip()
        for 업태 in ['소매업', '음식업']:
            행 = d[d[0] == 업태].iloc[0]
            가동[(f'{연도}-{월:02d}', 업태)] = int(행[4])            # 당월
            가동[(f'{연도 - 1}-{월:02d}', 업태)] = int(행[7])        # 전년동월
            if 월 == 1:
                가동[(f'{연도 - 1}-12', 업태)] = int(행[5])          # 1월 파일의 전월 = 전년 12월
rows = []
for (연월, 업태), 값 in 가동.items():
    rows.append({'연월': 연월, '업태': 업태, '가동': 값})
stock = pd.DataFrame(rows)

# ==============================================================================
# [2] 월별 신규 사업자 수 : 신규사업자 현황Ⅱ 엑셀 5개 (2021~2025)
#   - 시트 (3)=1~6월, (4)=7~12월 / 0열 업종명 / (3)시트는 '연간 계' 열이 하나 더 있어 4열부터, (4)시트는 3열부터
#   - 업종 이름이 가동 파일과 달라서('음식점업' ↔ '음식업') 가동 파일 이름으로 맞춤
# ==============================================================================
rows = []
for 연도 in range(2021, 2026):
    for 시트, 시작월, 첫열 in [('(3)', 1, 4), ('(4)', 7, 3)]:
        d = pd.read_excel(f'./Data/신규사업자_{연도}.xlsx', sheet_name=시트, header=None)
        d[0] = d[0].astype(str).str.strip()
        for 업종, 업태 in [('소매업', '소매업'), ('음식점업', '음식업')]:
            행 = d[d[0] == 업종].iloc[0]
            for k in range(6):
                rows.append({'연월': f'{연도}-{시작월 + k:02d}', '업태': 업태, '신규': int(행[첫열 + k])})
new = pd.DataFrame(rows)

# ==============================================================================
# [3] 업태별 월별 폐업 역산
#   - 폐업(이번달) = 신규(이번달) − (가동(이번달) − 가동(지난달))
#   - 업태·연월 순으로 정렬 → 바로 윗줄이 같은 업태면 그 값이 '지난달'
# ==============================================================================
u = stock.merge(new, on=['연월', '업태'], how='inner')
u['연월'] = pd.to_datetime(u['연월'])
u = u.sort_values(['업태', '연월']).reset_index(drop=True)
전월 = []
for k in range(len(u)):
    전월.append(u['가동'][k - 1] if k > 0 and u['업태'][k] == u['업태'][k - 1] else None)
u['가동_전월'] = 전월
u = u.dropna(subset=['가동_전월']).reset_index(drop=True)
u['폐업'] = u['신규'] - (u['가동'] - u['가동_전월'])
u['순증'] = u['신규'] - u['폐업']
u['연도'] = u['연월'].dt.year

# 소매 + 음식 합산 (월별)
m = u.groupby('연월')[['가동', '신규', '폐업', '순증']].sum().reset_index()
print(m)

# 역산 검증 : 연간 합계를 국세청 공식 폐업자 수(개인)와 비교  (2021년은 2월부터라 1월이 빠져 있음)
공식 = {('소매업', 2021): 189882, ('소매업', 2022): 206574, ('소매업', 2023): 268080, ('소매업', 2024): 289389, ('소매업', 2025): 269757,
       ('음식업', 2021): 123794, ('음식업', 2022): 131801, ('음식업', 2023): 152520, ('음식업', 2024): 148123, ('음식업', 2025): 137467}
연합 = u.groupby(['업태', '연도'])[['신규', '폐업', '순증']].sum().reset_index()
공식값 = []
for k in range(len(연합)):
    공식값.append(공식[(연합['업태'][k], 연합['연도'][k])])
연합['공식폐업'] = 공식값
연합['오차(%)'] = ((연합['폐업'] / 연합['공식폐업'] - 1) * 100).round(1)
print(연합)

# ==============================================================================
# [그림 1] 소매+음식 월별 신규 vs 폐업(역산) + 순증
# ==============================================================================
fig, ax = plt.subplots(2, 1, figsize=(12, 8), sharex=True)
ax[0].plot(m['연월'], m['신규'], marker='.', color='royalblue', label='신규(개업)')
ax[0].plot(m['연월'], m['폐업'], marker='.', color='crimson', label='폐업(역산)')
ax[0].set_ylabel('명')
ax[0].set_title('소매·음식점 월별 개업 vs 폐업 (2021.02~2025.12)')
ax[0].legend()
ax[0].grid(alpha=0.3)

색 = ['seagreen' if v >= 0 else 'crimson' for v in m['순증']]
ax[1].bar(m['연월'], m['순증'], width=20, color=색)
ax[1].axhline(0, color='gray', linewidth=1)
ax[1].set_ylabel('순증 (개업 - 폐업, 명)')
ax[1].set_title('월별 순증 — 빨간 막대 = 문 닫은 가게가 더 많은 달')
ax[1].grid(alpha=0.3, axis='y')
plt.tight_layout()
plt.show()

# ==============================================================================
# [그림 2] 소매업 vs 음식점 : 연도별 순증 + 가동 사업자 수 추이
#   - 왼쪽 : 연도별 순증(개업 − 폐업) — 음식점만 2024년부터 마이너스
#   - 오른쪽 : 12월말 가동 사업자 수 (2021년 = 100) — 소매는 계속 늘고, 음식점은 2023년부터 감소
# ==============================================================================
연말 = stock[stock['연월'].str.endswith('-12')].copy()
연말['연도'] = 연말['연월'].str[:4].astype(int)
연말 = 연말.sort_values(['업태', '연도']).reset_index(drop=True)
기준값 = []
for k in range(len(연말)):
    기준값.append(연말[(연말['업태'] == 연말['업태'][k]) & (연말['연도'] == 2021)]['가동'].iloc[0])
연말['지수'] = (연말['가동'] / 기준값 * 100).round(1)
print(연말)

fig, ax = plt.subplots(1, 2, figsize=(14, 5))
sns.barplot(data=연합, x='연도', y='순증', hue='업태', ax=ax[0], palette=['darkgray', 'crimson'])
ax[0].axhline(0, color='black', linewidth=1)
ax[0].set_title('업태별 연도별 순증 (개업 - 폐업, 명)')
ax[0].grid(alpha=0.3, axis='y')

for 업태, 색 in [('소매업', 'darkgray'), ('음식업', 'crimson')]:
    t = 연말[연말['업태'] == 업태]
    ax[1].plot(t['연도'], t['지수'], marker='o', color=색, linewidth=2, label=업태)
    for k in range(len(t)):
        ax[1].text(t['연도'].iloc[k], t['지수'].iloc[k] + 0.8, t['지수'].iloc[k], ha='center', fontsize=9)
ax[1].axhline(100, color='black', linewidth=1)
ax[1].set_xticks([2021, 2022, 2023, 2024, 2025])
ax[1].set_title('12월말 가동 사업자 수 (2021년 = 100)')
ax[1].legend()
ax[1].grid(alpha=0.3)
plt.tight_layout()
plt.show()


# ##############################################################################
#  배경 2. 왜 문을 닫았나 — 국세청 「폐업자 현황 Ⅳ (폐업사유, 지역, 업태)」 2021~2025
#   - 연도마다 엑셀 1개 (폐업사유_2021.xlsx ~ 폐업사유_2025.xlsx)
#   - 시트 (2)·(3)·(4) : 일반·간이·면세 사업자 (= 개인사업자) 의 지역별·업태별
#   - 열 : 0 구분 / 2 총계 / 3 사업부진 / 4 행정처분 / 5 계절사업 / 6 법인전환
#          7 면세포기·적용 / 8 양도·양수 / 9 해산·합병 / 10 기타(미신고 등)
# ##############################################################################
사유 = ['총계', '사업부진', '행정처분', '계절사업', '법인전환', '면세포기적용', '양도양수', '해산합병', '기타']

# ==============================================================================
# [4] 연도 × 업태 (개인사업자 = 일반 + 간이 + 면세 시트 합산)
#   - '지역별' 아래 줄부터 시도, '업태별' 아래 줄부터 업태
#   - 업태 이름에 줄바꿈(\n) 있음 → 제거
# ==============================================================================
rows = []
for 연도 in range(2021, 2026):
    for 시트 in ['(2)', '(3)', '(4)']:
        d = pd.read_excel(f'./Data/폐업사유_{연도}.xlsx', sheet_name=시트, header=None)
        구분 = None
        for i in range(9, d.shape[0]):
            이름 = str(d.iloc[i, 0]).replace('\n', '').strip()
            if 이름 == '지역별':
                구분 = '시도'
                continue
            if 이름 == '업태별':
                구분 = '업태'
                continue
            if 구분 is None or not str(d.iloc[i, 2]).isdigit():    # 주석·빈 줄 건너뜀
                continue
            row = {'연도': 연도, '구분': 구분, '항목': 이름}
            for k in range(9):
                row[사유[k]] = int(d.iloc[i, 2 + k])
            rows.append(row)
상세 = pd.DataFrame(rows)
상세 = 상세.groupby(['연도', '구분', '항목'])[사유].sum().reset_index()     # 일반+간이+면세 합산
업태 = 상세[(상세['구분'] == '업태') & (상세['항목'].isin(['소매업', '음식업']))]
소음 = 업태.groupby('연도')[사유].sum().reset_index()                         # 소매 + 음식 합산
소음['사업부진비중'] = (소음['사업부진'] / 소음['총계'] * 100).round(1)
업태 = 업태.copy()
업태['사업부진비중'] = (업태['사업부진'] / 업태['총계'] * 100).round(1)
print(소음)
print(업태[['연도', '항목', '총계', '사업부진', '사업부진비중']])

# ==============================================================================
# [그림 3] 소매+음식 폐업 사유 구성 (만 명) + 업태별 '사업부진' 비중 추이
# ==============================================================================
fig, ax = plt.subplots(1, 2, figsize=(14, 5))
아래 = [0] * len(소음)
for s in ['사업부진', '양도양수', '행정처분', '법인전환', '해산합병', '계절사업', '면세포기적용', '기타']:
    값 = list(소음[s] / 10000)
    ax[0].bar(소음['연도'], 값, bottom=아래, label=s)
    아래 = [아래[k] + 값[k] for k in range(len(값))]
ax[0].set_title('소매·음식점 연도별 폐업 사유 구성 (만 명)')
ax[0].legend(fontsize=8, ncol=2)

for 이름, 색 in [('소매업', 'darkgray'), ('음식업', 'crimson')]:
    t = 업태[업태['항목'] == 이름]
    ax[1].plot(t['연도'], t['사업부진비중'], marker='o', color=색, linewidth=2, label=이름)
    for k in range(len(t)):
        ax[1].text(t['연도'].iloc[k], t['사업부진비중'].iloc[k] + 0.4, t['사업부진비중'].iloc[k], ha='center', fontsize=9)
ax[1].set_xticks([2021, 2022, 2023, 2024, 2025])
ax[1].set_ylim(45, 65)
ax[1].set_title("업태별 '사업부진(장사가 안 돼서)' 폐업 비중 (%)")
ax[1].legend()
ax[1].grid(alpha=0.3)
plt.tight_layout()
plt.show()